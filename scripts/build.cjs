const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const output='// Generated by scripts/build.cjs from src/experience.js, src/progress.js, src/insights.js, src/study.js and src/app.js.\n'+
  ['src/experience.js','src/progress.js','src/insights.js','src/study.js','src/app.js'].map(file=>fs.readFileSync(path.join(root,file),'utf8')).join('\n');
const target=path.join(root,'dist/app.js');
if(process.argv.includes('--check')){
  if(fs.readFileSync(target,'utf8')!==output){console.error('dist/app.js is stale. Run npm run build and commit the result.');process.exit(1)}
}else{fs.writeFileSync(target,output);console.log('Built dist/app.js');}
